#pragma once

#include <cstdint>
#include <string>

namespace iskra {

// Внутри эмулятора текст живёт в КОИ-8, как на самой машине. Перекодировка
// нужна только на границе: дампы экрана, имена файлов, заголовок окна.
uint32_t koi8_to_unicode(uint8_t code);

// Обратное для одного знака: нужно оконным хостам, которым система отдаёт
// нажатие сразу кодовой точкой Юникода. Непредставимый знак даёт false и
// вопросительный знак в code.
bool unicode_to_koi8(uint32_t cp, uint8_t & code);

// --- семибитная граница машины ---------------------------------------------
//
// Знакогенератор «Искры» держит 96 знаков — коды 20-7F кодировки КОИ-7 Н2
// (рис. 3.1 руководства по БОСГИ). Нижняя половина у КОИ-7 Н2 и КОИ-8
// совпадает знак в знак, а прописная кириллица КОИ-8 (E0-FF) в семибитной
// кодировке лежит по адресам 60-7F, то есть ровно со сброшенным старшим
// битом. Отличий два, и оба видны на том же рисунке: 5F — не подчёркивание,
// а Ъ (в КОИ-8 он в FF), и 7F пуст.

// Клавиатура: строчные буквы приводятся к прописным — строчных у машины
// нет вовсе, ни латинских, ни кириллических, и клавиша выдаёт прописную.
//
// **Старший бит здесь не сбрасывается, и это не оплошность.** У машины он и
// не возникает: она семибитная целиком. Эмулятор же держит текст в КОИ-8 —
// в нём лежат и листинги корпуса, и байты на дискете, — а семибитный код
// кириллической буквы в КОИ-8 занят латинской: сбрось бит на клавиатуре, и
// набранное «ПРИВЕТ» осело бы в тексте программы как «PRIWET». Поэтому бит
// сбрасывается там, где его сбрасывает и машина, — на выходе к экрану.
uint8_t koi8_upper(uint8_t code);

// Экран: код КОИ-8 → код КОИ-7 Н2, который уходит в знакогенератор.
// Приведение к прописным входит сюда же: строчных глифов нет.
uint8_t koi8_to_koi7(uint8_t code);

// Обратное: ячейка экрана → КОИ-8, чтобы дамп экрана можно было выдать в
// UTF-8 обычным koi8_to_utf8. Пустая позиция 7F выдаётся пробелом — на
// экране она и есть пустая.
uint8_t koi7_to_koi8(uint8_t code);

void koi8_to_utf8(const uint8_t * data, unsigned len, std::string & out);
std::string koi8_to_utf8(const uint8_t * data, unsigned len);

// Обратное направление нужно на входе: листинги корпуса лежат в UTF-8, а
// внутри эмулятора всё в КОИ-8. Непредставимый символ даёт false, но
// перекодировка идёт до конца, подставляя вопросительный знак.
bool utf8_to_koi8(const std::string & in, std::string & out);

} // namespace iskra