#pragma once

#include <cstdint>

namespace iskra {

// Коды клавиш восстановлены по корпусу (`docs/format.md`, разд. 12): книга
// их не даёт вовсе — приложение 1 перечисляет коды управления **дисплеем**,
// а не клавиатурой. Клавиши редактирования — обычные, а не спецфункций: в
// `BAM3` они приходят на первую строку `KEYIN`, а вторая занята зоной 8.
//
// Ключ ко всему — `BAM3` 1000: шесть кодов `AA`–`AF` переводятся там списком
// пар в маленькие номера, и обработчики рядом называют каждую клавишу сами.
enum KeyCode {
    KEY_CR         = 0x85,  // CR/LF — конец набора (BAM 182/186)
    KEY_BACKSPACE  = 0x89,  // забой со стиранием (BAM3 1060)
    KEY_EDIT       = 0x9A,  // переход в режим правки (EDITOR 6312)
    KEY_RECALL     = 0x9B,  // вызов строки на экран (BAM3 1140)
    KEY_INSERT     = 0x9C,  // вставка пробела — **не доказан**, по порядку клавиш
    KEY_DELETE     = 0x9D,  // удаление символа — **не доказан**, по порядку клавиш
    KEY_ERASE      = 0x9E,  // стереть правую часть строки (BAM3 1250)
    KEY_LINE_ERASE = 0x9F,  // стереть всю строку (BAM3 1110)
    KEY_UP         = 0xAA,  // курсор на строку вверх
    KEY_LEFT5      = 0xAB,  // курсор на 5 позиций влево
    KEY_LEFT       = 0xAC,  // курсор на позицию влево
    KEY_RIGHT      = 0xAD,  // курсор на позицию вправо
    KEY_RIGHT5     = 0xAE,  // курсор на 5 позиций вправо
    KEY_DOWN       = 0xAF   // курсор на строку вниз
};

// Клавиша редактирования либо конца набора — то, что построчный ввод
// разбирает сам, а не печатает. Всё прочее в диапазоне `80`–`BF` машина
// тоже считает не-символом (`EDITOR` 2520), но что там за клавиши, корпус
// не показывает.
inline bool is_edit_key(uint8_t code)
{
    return code == KEY_CR || code == KEY_BACKSPACE ||
           (code >= KEY_EDIT && code <= KEY_LINE_ERASE) ||
           (code >= KEY_UP && code <= KEY_DOWN);
}

// Клавиши управления машиной: кодов у них нет вовсе, и программе они не
// достаются — их разбирает сама машина. Идут они не очередью нажатий, а
// отдельным ящиком (`Host::take_control_key`): `HALT` должен прерывать
// счёт и тогда, когда программа клавиатуру не опрашивает.
enum ControlKey {
    CK_NONE = 0,
    CK_HALT,          // останов счёта; при остановленной программе — шаг
    CK_CONTINUE,      // продолжить со следующего оператора (разд. 11.1)
    CK_RESET,         // «прекращение выполнения операций и очистка экрана»
    CK_STMT_NUMBER    // подставить номер следующей строки (разд. 3.2)
};

} // namespace iskra
