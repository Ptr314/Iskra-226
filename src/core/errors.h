#pragma once

namespace iskra {

// «При возникновении ошибки в программе в символьную переменную 1 заносится
// код ошибки (два или четыре символа)» (руководство, разд. 11.6). Двузначные
// коды — программные ошибки, четырёхзначные вида 80XX — ошибки ввода-вывода.
//
// Полной таблицы кодов в руководстве нет. Известно следующее:
//
//   03    математическая ошибка          книга, пример 11.11
//   71    такой файл уже есть            EDITOR 7850…7885
//   72    старый файл мал                EDITOR 7855 → 7673 → 7885
//   73    такого файла нет               EDITOR 7855 → 7865
//   74/75 файл слишком велик             EDITOR 7850 → 7870
//   80XX  ошибки ввода-вывода            книга, разд. 11.5
//
// Коды 71…75 выведены из обработчика ошибок `EDITOR`: он сравнивает код с
// литералом и печатает своё сообщение. Это сильное свидетельство, но всё же
// толкование чужой программы, а не таблица из документации.
namespace err {

const char * const MATH        = "03";
const char * const FILE_EXISTS = "71";
const char * const FILE_SMALL  = "72";
const char * const NO_FILE     = "73";
const char * const FILE_BIG    = "74";

// Код не установлен. Ставится там, где ошибка машине известна, а её номер
// нам — нет. Управление обработчику передаётся как обычно, но сравнение
// с настоящим кодом не сойдётся — и это лучше выдуманного номера.
const char * const UNKNOWN     = "??";

} // namespace err

// Куда передаётся управление при ошибке (руководство, разд. 11.6).
enum ErrMode {
    EM_OFF,      // `ON ERROR` без параметров отменяет обработку
    EM_GOTO,     // переход без возврата
    EM_THEN,     // RETURN вернёт на оператор ПОСЛЕ ошибочного
    EM_GOSUB     // RETURN вернёт НА ошибочный оператор
};

} // namespace iskra