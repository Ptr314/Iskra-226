#pragma once

#include <cstdint>

#include "core/keys.h"
#include "core/raster.h"
#include "core/screen.h"

namespace iskra {

// Единственное, что ядро знает о внешнем мире. Реализации: host_headless
// (для автотестов, без зависимостей) и host_sdl2 (окно, он же WASM).
//
// Ядру не полагается включать ничего, кроме этого заголовка: ни SDL,
// ни чего бы то ни было стороннего.
class Host
{
public:
    // Сектор гибкого диска «Искры»: 2 служебных байта + 254 данных.
    static const unsigned SECTOR_SIZE = 256;

    virtual ~Host() {}

    // --- Символьная половина БОСГИ, ФАУ 05 -------------------------------
    virtual Screen & screen() = 0;

    // Показать накопленные изменения экрана и обработать события хоста.
    // Возвращает false, если пользователь закрыл окно.
    virtual bool present() = 0;

    // --- Графическая половина БОСГИ, ФАУ 10 ------------------------------
    // Трубка одна, а устройств в таблице ФАУ два: `05` «блок отображения
    // символьной информации» и `10` «блок отображения графической». Знаки
    // рисует аппаратный знакогенератор, точки — растр; здесь они и разведены.
    virtual Raster & raster() { return raster_; }

    // Лист графопостроителя, ФАУ 14. Своего растра у нас для него нет и
    // взяться ему неоткуда: книга про устройство говорит два слова
    // («планшетный»), разрешения не называет, а размер картинки не задаётся
    // нигде — ни в буфере, ни в его заголовке. Поэтому лист берётся в тех же
    // координатах, что и буфер: это единственная система координат, которая
    // в данных есть. Хост волен подсунуть свой.
    virtual Raster & plotter() { return plotter_; }

    // Куда выкладывать буфер, отправленный `¤COPY /<адрес>`. Ноль значит
    // «такого устройства нет», и программа останавливается — как и при
    // блочном обмене с неизвестным адресом.
    virtual Raster * plot_surface(uint8_t addr)
    {
        if (addr == 0x10) return &raster();
        if (addr == 0x14) return &plotter();
        return 0;
    }

    // --- Клавиатура, ФАУ 01 ----------------------------------------------
    // Неблокирующее чтение: false, если нажатий не было.
    virtual bool poll_key(uint8_t & code) = 0;

    // Была ли последняя прочитанная клавиша клавишей специальных функций.
    // Оператор `KEYIN` разводит два этих случая по разным строкам, а по
    // одному коду их не различить: у клавиш спецфункций коды маленькие, и
    // там же живут управляющие символы. Спрашивать сразу после poll_key();
    // у хостов, где таких клавиш нет, всегда false.
    virtual bool key_was_special() const { return false; }

    // Клавиши управления машиной — HALT/STEP, CONTINUE, RESET, STMT NUMBER.
    // Кодов у них нет вовсе (`docs/format.md`, разд. 12), и программе они не
    // достаются, поэтому идут не очередью нажатий, а отдельным ящиком на
    // одну клавишу: `HALT` обязан прерывать счёт и тогда, когда программа
    // клавиатуру не опрашивает. Спрашивает исполнитель по ходу прогона и
    // диалог между нажатиями; ящик при этом опустошается.
    virtual ControlKey take_control_key() { return CK_NONE; }

    // Ждать нажатия либо клавиши управления. Ждёт хост, а не ядро: у окна
    // это прокрутка событий, у хоста без окна — заготовленная очередь, и
    // false значит «ввода больше не будет» (конец сценария, закрытое окно).
    // Ядру в обоих случаях остаётся одно и то же — прекратить чтение.
    virtual bool wait_input(uint8_t & code, ControlKey & ck)
    {
        for (;;) {
            ck = take_control_key();
            if (ck != CK_NONE) { code = 0; return true; }
            if (poll_key(code)) return true;
            if (!present()) return false;
        }
    }

    // Ждать именно нажатия: клавиши управления машиной программе не видны,
    // и `INPUT` их пропускает. Не виртуальный — ждёт всё равно wait_input().
    bool wait_key(uint8_t & code)
    {
        for (;;) {
            ControlKey ck = CK_NONE;
            if (!wait_input(code, ck)) return false;
            if (ck == CK_NONE) return true;
        }
    }

    // --- Блочный обмен с устройством по ФАУ -------------------------------
    // `DATA SAVE BT` и `DATA LOAD BT` шлют и принимают блок байтов, а какое
    // это устройство — параметр оператора. В корпусе их семь разных: экран
    // (05), АЦПУ (0C), графопостроитель (14), телекоммуникационный
    // интерфейс (34 передатчик, 35 приёмник) и другие.
    //
    // По умолчанию разбирается два адреса: экран (05) и АЦПУ (0C). Для
    // всего прочего возвращается false — «такого устройства нет», и
    // программа останавливается. Молча терять данные нельзя: обмен выглядел
    // бы работающим.
    //
    // ОСТОРОЖНО: у `print_char` умолчание пустое, и адрес 0C принимается в
    // любом случае. Хост, который его не переопределил, теряет печать
    // молча — ровно то, чего абзац выше запрещает. Свои приёмники есть у
    // всех трёх наших хостов (окно, командная строка, автотесты); новому
    // хосту его надо завести, иначе ветку 0C у него придётся гасить.
    virtual bool device_write(uint8_t addr, const uint8_t * data, unsigned len)
    {
        if (addr == 0x05) { screen().write(data, len); return true; }
        if (addr == 0x0C) {
            for (unsigned i = 0; i < len; ++i) print_char(data[i]);
            return true;
        }
        // Графическая половина БОСГИ принимает управляющие коды. Разобраны
        // они по руководству на 2282 Graphic CRT — ближайшего родственника
        // устройства у Wang (`docs/format.md`, разд. 5):
        //
        //   `03` гасит поле, `0E` поднимает перо, `0F` опускает, `0D`
        //   задаёт размер знака.
        //
        // Из них рисует только `03`, и он же подтверждён независимо: своя
        // таблица кодов дисплея даёт `03` = КТ, а `GRAFISN` 110 ставит
        // `PRINT HEX(03)` и `PRINT /10,HEX(03)` подряд — гасится текст, а
        // следом графика.
        //
        // Остальные трое **сами по себе ничего не рисуют**: точку кладёт
        // только двоичный вектор (`E0` длинный, `E6` короткий), а его мы не
        // принимаем — прямого вывода в обход буфера у нас нет. В корпусе
        // вектора и не встречаются: все коды стоят поодиночке.
        //
        // Пакет принимается целиком или не принимается вовсе: попался
        // неизвестный код — отказ, и программа останавливается (ключ `-i`
        // велит такое пропускать). Выполнить половину пакета и смолчать про
        // остальное было бы хуже всего.
        if (addr == 0x10) {
            for (unsigned i = 0; i < len; ++i) {
                const uint8_t c = data[i];
                if (c != 0x03 && c != 0x0D && c != 0x0E && c != 0x0F)
                    return false;
            }
            for (unsigned i = 0; i < len; ++i)
                if (data[i] == 0x03) raster().clear();
            return true;
        }
        return false;
    }

    // Ввод блоком. Устройств ввода, кроме клавиатуры, у хоста нет вовсе.
    virtual bool device_read(uint8_t addr, uint8_t * data, unsigned len)
    {
        (void)addr; (void)data; (void)len;
        return false;
    }

    // --- НГМД, ФАУ 18 ----------------------------------------------------
    // Число секторов на устройстве; 0 — устройство отсутствует.
    virtual unsigned disk_sectors(unsigned drive) const = 0;
    virtual bool disk_read(unsigned drive, unsigned sector, uint8_t * buf) = 0;
    virtual bool disk_write(unsigned drive, unsigned sector, const uint8_t * buf) = 0;

    // --- АЦПУ, ФАУ 0C ----------------------------------------------------
    // Приёмник печати. Умолчание пустое, и каждый хост заводит свой:
    // окно — ленту отдельным окном, командная строка — вывод после прогона,
    // автотесты — буфер. См. `host_common/printer.*`.
    virtual void print_char(uint8_t) {}

    // --- Прочее ----------------------------------------------------------
    // Миллисекунды с запуска: для оператора TIME и заставок.
    virtual uint32_t ticks_ms() const = 0;

protected:
    Raster raster_;
    Raster plotter_;
};

} // namespace iskra