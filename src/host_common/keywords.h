#pragma once

#include <cstdint>

namespace iskra {

// «В верхнем регистре нажатием каждой клавиши вводится то или иное ключевое
// слово Бейсика, что позволяет ускорить набор этих слов и исключить ошибки»
// (руководство, разд. 2.1). Слово при этом просто набирается в строку —
// своего кода у него нет: машина показывает его на экране, как набранное по
// буквам.
//
// Раскладка снята с рис. 2.2 (`docs/keyboard.svg`). Ключ — **знак**, а не
// положение клавиши: на «Искре» русская и латинская буквы сидят на одной
// клавише, а на PC они разъезжаются по раскладкам. Поэтому у каждого слова
// два входа, `Й` и `J`, и работает оно с любой раскладки.
//
// Возвращает 0, если слова у этого знака нет.
const char * keyword_for_char(uint8_t koi8);

// Функции зоны 5. У них на PC знаки те же, что у клавиш зоны 1 (`+`, `-`,
// `*`, `/`), и различить их можно только по положению — поэтому они сидят
// на арифметических клавишах цифрового блока. Значения kind — те же, что у
// `VK_ADD` и соседей, но перечислены здесь, чтобы host_common не знал про
// windows.h.
enum PadFunc { PAD_MUL = 0, PAD_ADD, PAD_SUB, PAD_DIV };
const char * keyword_for_pad(PadFunc kind);

} // namespace iskra
